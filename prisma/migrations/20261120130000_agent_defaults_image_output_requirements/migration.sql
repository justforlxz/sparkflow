-- 图片 Agent 的默认输出要求同步（MKACG-921），只改预置行，不动用户保存过的自定义配置。
--
-- 旧文案里有两处与当前契约相反：
-- 1. 「按目标张数」：该参数已由 ADR 0008 取消（成品张数 = 本次原图张数），界面上没有这个输入项；
-- 2. 「不要加水印」：docs/prd/05 的实测结论是同模型下把「不要水印」写进提示词无效，
--    且 MUST NOT 禁止在实现里承诺无水印。
--
-- 不直接改 20261118010000_agent_config：那条迁移已经应用过，改写会让
-- `prisma migrate dev` 判定「迁移被修改」并要求重置数据库。改为新增一条迁移覆盖预置行，
-- 新装环境（旧迁移插入 + 本条更新）与老库升级（本条更新）都得到新文案。
UPDATE "agent_config"
SET "output_requirements" = '每张原图各生成一张完整可用的成品图，不要拼接。'
WHERE "type" = 'image'
  AND "output_requirements" = '按目标张数输出图片，每张都是完整可用的成品图，不要拼接，不要加水印。';
